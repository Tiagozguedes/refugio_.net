DECLARE
V_COUNT INTEGER;
BEGIN
SELECT COUNT(TABLE_NAME) INTO V_COUNT from USER_TABLES where TABLE_NAME = 'T_RFG_EF_MIGRACOES';
IF V_COUNT = 0 THEN
Begin
BEGIN 
EXECUTE IMMEDIATE 'CREATE TABLE 
"T_RFG_EF_MIGRACOES" (
    "MigrationId" NVARCHAR2(150) NOT NULL,
    "ProductVersion" NVARCHAR2(32) NOT NULL,
    CONSTRAINT "PK_T_RFG_EF_MIGRACOES" PRIMARY KEY ("MigrationId")
)';
END;

End;

END IF;
EXCEPTION
WHEN OTHERS THEN
    IF(SQLCODE != -942)THEN
        RAISE;
    END IF;
END;
/

BEGIN 
EXECUTE IMMEDIATE 'CREATE TABLE 
"T_RFG_REFUGIO" (
    "ID" NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    "NOME" NVARCHAR2(150) NOT NULL,
    "TIPO" NVARCHAR2(30) NOT NULL,
    "CEP" NVARCHAR2(9) NOT NULL,
    "ENDERECO" NVARCHAR2(200) NOT NULL,
    "BAIRRO" NVARCHAR2(100) NOT NULL,
    "CAPACIDADE" NUMBER(10) NOT NULL,
    "ABRE" VARCHAR2(5) NOT NULL,
    "FECHA" VARCHAR2(5) NOT NULL,
    "ACESSIVEL" NUMBER(1) NOT NULL,
    "ATIVO" NUMBER(1) NOT NULL,
    CONSTRAINT "PK_T_RFG_REFUGIO" PRIMARY KEY ("ID")
)';
END;
/

BEGIN 
EXECUTE IMMEDIATE 'CREATE TABLE 
"T_RFG_USUARIO" (
    "ID" NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    "NOME" NVARCHAR2(150) NOT NULL,
    "EMAIL" NVARCHAR2(200) NOT NULL,
    "SENHA_HASH" NVARCHAR2(200) NOT NULL,
    "PAPEL" NVARCHAR2(20) NOT NULL,
    "BAIRRO" NVARCHAR2(100),
    "TELEFONE" NVARCHAR2(20),
    "CONTATO_EMERGENCIA_NOME" NVARCHAR2(150),
    "CONTATO_EMERGENCIA_TELEFONE" NVARCHAR2(20),
    "CRIADO_EM" TIMESTAMP(7) WITH TIME ZONE NOT NULL,
    CONSTRAINT "PK_T_RFG_USUARIO" PRIMARY KEY ("ID")
)';
END;
/

BEGIN 
EXECUTE IMMEDIATE 'CREATE TABLE 
"T_RFG_RESERVA" (
    "ID" NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    "IDOSO_ID" NUMBER(19) NOT NULL,
    "REFUGIO_ID" NUMBER(19) NOT NULL,
    "DATA_RESERVA" DATE NOT NULL,
    "STATUS" NVARCHAR2(20) NOT NULL,
    "CRIADO_EM" TIMESTAMP(7) WITH TIME ZONE NOT NULL,
    "CHAVE_IDEMPOTENCIA" NVARCHAR2(100) NOT NULL,
    CONSTRAINT "PK_T_RFG_RESERVA" PRIMARY KEY ("ID"),
    CONSTRAINT "FK_T_RFG_RESERVA_REFUGIO" FOREIGN KEY ("REFUGIO_ID") REFERENCES "T_RFG_REFUGIO" ("ID") ON DELETE CASCADE,
    CONSTRAINT "FK_T_RFG_RESERVA_USUARIO" FOREIGN KEY ("IDOSO_ID") REFERENCES "T_RFG_USUARIO" ("ID")
)';
END;
/

CREATE INDEX "IX_T_RFG_REFUGIO_BAIRRO" ON "T_RFG_REFUGIO" ("BAIRRO")
/

CREATE INDEX "IX_T_RFG_RESERVA_IDOSO_ID_DATA_RESERVA" ON "T_RFG_RESERVA" ("IDOSO_ID", "DATA_RESERVA")
/

CREATE INDEX "IX_T_RFG_RESERVA_REFUGIO_ID_DATA_RESERVA_STATUS" ON "T_RFG_RESERVA" ("REFUGIO_ID", "DATA_RESERVA", "STATUS")
/

CREATE UNIQUE INDEX "UX_T_RFG_RESERVA_IDOSO_ID_CHAVE_IDEMPOTENCIA" ON "T_RFG_RESERVA" ("IDOSO_ID", "CHAVE_IDEMPOTENCIA")
